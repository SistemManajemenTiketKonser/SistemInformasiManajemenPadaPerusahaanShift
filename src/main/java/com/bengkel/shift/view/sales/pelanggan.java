    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        Pelanggan p = inputPelanggan(null);
        if (p == null) return;
        if (controller.tambah(p)) {
            JOptionPane.showMessageDialog(this, "Pelanggan berhasil ditambahkan!");
            muatTabel();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan pelanggan. Periksa kembali data dan koneksi database.", "Gagal", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private Pelanggan inputPelanggan(Pelanggan dataLama) {
        javax.swing.JTextField nama = new javax.swing.JTextField(dataLama == null ? "" : dataLama.getNamaPelanggan(), 22);
        javax.swing.JTextField telepon = new javax.swing.JTextField(dataLama == null ? "" : dataLama.getNoHp(), 22);
        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 1, 5, 5));
        panel.add(new javax.swing.JLabel("Nama Pelanggan"));
        panel.add(nama);
        panel.add(new javax.swing.JLabel("Nomor Telepon"));
        panel.add(telepon);
        int hasil = JOptionPane.showConfirmDialog(this, panel,
                dataLama == null ? "Tambah Pelanggan" : "Ubah Data Pelanggan",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (hasil != JOptionPane.OK_OPTION) return null;
        Pelanggan p = new Pelanggan();
        if (dataLama != null) p.setIdPelanggan(dataLama.getIdPelanggan());
        p.setNamaPelanggan(nama.getText().trim());
        p.setNoHp(telepon.getText().trim());
        return p;
    }

    private void muatTabel() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        for (Pelanggan p : controller.tampilSemua()) {
            model.addRow(new Object[]{p.getIdPelanggan(), p.getNamaPelanggan(), p.getNoHp()});
        }
    }

    private void ubahPelanggan() {
        int baris = jTable1.getSelectedRow();
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Pilih pelanggan yang ingin diubah terlebih dahulu.");
            return;
        }
        int row = jTable1.convertRowIndexToModel(baris);
        Pelanggan lama = new Pelanggan();
        lama.setIdPelanggan(Integer.parseInt(jTable1.getModel().getValueAt(row, 0).toString()));
        lama.setNamaPelanggan(jTable1.getModel().getValueAt(row, 1).toString());
        lama.setNoHp(jTable1.getModel().getValueAt(row, 2).toString());
        Pelanggan baru = inputPelanggan(lama);
        if (baru == null) return;
        try {
            if (controller.ubah(baru)) {
                JOptionPane.showMessageDialog(this, "Data pelanggan berhasil diubah!");
                muatTabel();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal mengubah data pelanggan. Periksa kembali data dan koneksi database.", "Gagal", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validasi Input", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void hapusPelanggan() {
        int baris = jTable1.getSelectedRow();
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Pilih pelanggan yang ingin dihapus terlebih dahulu.");
            return;
        }
        int row = jTable1.convertRowIndexToModel(baris);
        int id = Integer.parseInt(jTable1.getModel().getValueAt(row, 0).toString());
        int konfirmasi = JOptionPane.showConfirmDialog(this,
                "Apakah Anda yakin ingin menghapus pelanggan ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            if (controller.hapus(id)) {
                JOptionPane.showMessageDialog(this, "Data pelanggan berhasil dihapus!");
                muatTabel();
            } else {
                JOptionPane.showMessageDialog(this,
                        "Pelanggan tidak dapat dihapus karena masih digunakan oleh data kendaraan atau transaksi.",
                        "Data Memiliki Relasi", JOptionPane.WARNING_MESSAGE);
            }
        }
    }

