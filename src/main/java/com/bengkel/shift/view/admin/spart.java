    /** Mengambil data terbaru dari database dan menampilkannya pada tabel. */
    private void muatTabel() {
        try {
            jTable1.setModel(dataController.tampilkan("sparepart"));
            jTable1.setAutoCreateRowSorter(true);
        } catch (java.sql.SQLException ex) {
            JOptionPane.showMessageDialog(this,
                "Data sparepart gagal dimuat. Periksa koneksi MySQL dan database db_shift2.\n" + ex.getMessage(),
                "Kesalahan Database", JOptionPane.ERROR_MESSAGE);
        }
    }

